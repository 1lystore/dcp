/**
 * Vault connect bridge.
 *
 * The relay's OAuth AS must ask the VAULT that issued a connect-link to (a) redeem
 * it for an agent (producing the on-device match-code) and (b) report whether the
 * owner has approved. The vault — not the relay — is the source of truth: it
 * verifies the connect-link signature, generates the match-code, and runs the
 * on-device approval. The relay only orchestrates and issues tokens.
 *
 * This is the CONTROL plane (authorization handshake), distinct from the encrypted
 * DATA plane (vault operations). It carries no vault secrets and no key material.
 *
 * Production backs this with the relay↔vault WebSocket control channel; tests
 * inject a fake implementation.
 */

export interface BridgeRedeemInput {
  /** Vault that issued the link (routing target). */
  vaultId: string;
  /** The opaque connect-link token; the VAULT verifies + decodes it. */
  connectLink: string;
  /** Stable identifier for the redeeming agent — its DPoP JWK thumbprint (jkt). */
  redeemerKey: string;
  /** Server-derived source IP (for the on-device approval facts). */
  sourceIp?: string;
}

export interface BridgeRedeemResult {
  ok: boolean;
  agentId?: string;
  /** Match-code generated by the vault, shown on-device and returned to the agent. */
  matchCode?: string;
  reason?: string;
}

/**
 * Link-less pairing: a standard OAuth MCP client connected with JUST the vault's
 * MCP URL (no connect-link secret). The relay asks the vault to open an on-device
 * approval directly. The vault gates this on its "pairing window" + rate-limit and
 * returns the same {agentId, matchCode} a redeem would.
 */
export interface BridgePairingInput {
  /** Vault addressed by the MCP URL (routing target). */
  vaultId: string;
  /** Redeeming agent's DPoP JWK thumbprint (jkt), or a TOFU placeholder for the
   *  browser auth-code flow where the key is bound later at /token. */
  redeemerKey: string;
  /** Server-derived source IP (for the on-device approval facts). */
  sourceIp?: string;
  /** Untrusted client display name (from Dynamic Client Registration). */
  clientName?: string;
  /** Requested scope (space-delimited); the vault decides what to actually grant. */
  scope?: string;
}

export interface BridgeApprovalInput {
  vaultId: string;
  agentId: string;
}

export interface BridgeApprovalResult {
  status: 'pending' | 'approved' | 'denied' | 'revoked' | 'unknown';
  /** Authoritative scope granted by the vault (only meaningful once approved). */
  scope?: string;
  /** Authoritative budget (display/audit). */
  budget?: { daily: number; currency: string; auto_approve_under: number };
}

export interface VaultConnectBridge {
  redeem(input: BridgeRedeemInput): Promise<BridgeRedeemResult>;
  approvalStatus(input: BridgeApprovalInput): Promise<BridgeApprovalResult>;
  /**
   * Open a link-less on-device approval (the paste-URL flow). Optional so existing
   * (e.g. test) bridges keep working; when absent, the relay falls back to the
   * connect-link form and the URL-only path returns a 'pairing_unsupported' error.
   */
  requestPairing?(input: BridgePairingInput): Promise<BridgeRedeemResult>;
}

/** Default bridge used when no vault control channel is wired — fails closed. */
export class UnavailableVaultBridge implements VaultConnectBridge {
  async redeem(): Promise<BridgeRedeemResult> {
    return { ok: false, reason: 'vault_unreachable' };
  }
  async approvalStatus(): Promise<BridgeApprovalResult> {
    return { status: 'unknown' };
  }
  async requestPairing(): Promise<BridgeRedeemResult> {
    return { ok: false, reason: 'vault_unreachable' };
  }
}

/**
 * Data-plane bridge: forward an AUTHORIZED MCP request to the vault. The facade
 * has already verified the access token (audience) + DPoP proof; this carries the
 * authenticated agent identity so the vault can apply the right scopes/budget and
 * pop an on-device consent for sensitive actions.
 */
export interface AuthedMcpRequest {
  vaultId: string;
  /** Authenticated agent id (the access token subject). */
  agentId: string;
  /** Granted scope (space-delimited) from the access token. */
  scope: string;
  /** DPoP key thumbprint the token is bound to. */
  jkt: string;
  /** The MCP JSON-RPC request body. */
  body: unknown;
}

export interface McpDataBridge {
  forward(req: AuthedMcpRequest): Promise<{ status: number; body: unknown }>;
}

/** Default MCP data bridge — not wired yet; signals the data plane is unavailable. */
export class UnavailableMcpBridge implements McpDataBridge {
  async forward(): Promise<{ status: number; body: unknown }> {
    return {
      status: 503,
      body: { error: 'data_plane_unavailable', error_description: 'MCP bridge not configured' },
    };
  }
}
